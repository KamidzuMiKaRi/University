#include <iostream>
#include <fstream>

using namespace std;

void ReadFile(float* arr, int n, const string& filename)	// запись из файла в массив
{
	ifstream f(filename);
	cout << "Перовначальный массив: ";
	for (int i = 0; i < n; i++) {
		if (!(f >> arr[i])) {
			cerr << "Ошибка: не удалось прочитать элемент массива из файла " << filename << endl;
			exit(1);
		}
		cout << arr[i] << " ";
	}
}

int main()
{
	setlocale(LC_ALL, "rus");
	int n, i=0;	// объявление переменных
	fstream f;
	cout << "Введите размер массива: ";
	do {
		cin >> n;
		if (n <= 0)
		{
			cout << "Некорректное значение, попытайтесь снова: ";
		}
	} while (n <= 0);	// цикл ввода правильного размера массива
	float* arr = new float[n];	// создание динамического массива
	f.open("3.txt", ios_base::in);	// открываем файл в режиме чтения
	if (f.fail())
		cout << "Ошибка открытия файла";	// если ошибка открытия, то выводим сообщение
	ReadFile(arr, n, "3.txt");	// записываем n элементов из файла в массив
	f.close();	// закрываем файл
	while (i < n)	// цикл удаления отрицательных чисел
	{
		if (arr[i] < 0)	// пока arr[i] не будет положительным, то массив сдвигается влево с шагом один
		{
			n--;	// размер массива тоже уменьшается на один
			for (int j = i; j < n; j++)
				arr[j] = arr[j + 1];	// присвоение текущему последующего
		}
		else
			i++;	// переходим к следующему элементу
	}
	cout << "\nМассив без отрицательных чисел: ";
	for (int i = 0; i < n; i++)	// вывод конечного массива
		cout << arr[i] << " ";
	delete[] arr;	// удаление дин. массива
}