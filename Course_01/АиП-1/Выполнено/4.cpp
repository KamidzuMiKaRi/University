#include <iostream>
#include <string>
#include <fstream>

using namespace std;

int main()
{
	setlocale(LC_ALL, "rus");
	string text;
	fstream f;
	int Len, k, min;
	f.open("4.txt", ios_base::in);	// открываем файл в режиме чтения
	if (f.fail())
		cout << "Ошибка открытия файла";	// если ошибка открытия, то выводим сообщение
	else
	{
		getline(f, text);	// перенос текста из файла в строку
		Len = text.length();	// длина строки
		k = 0;	// длина слова. изначально 0                                             
		min = 0;	//минимальное значение. изначально 0
		for (int i = 0; i < Len; i++) 
		{
			k++;	// счетчки длины слова
			if ((text[i + 1] == ' ') || (text[i + 1] == ',') || (text[i + 1] == '.') || (text[i + 1] == '\0'))  // если след символ пробел, запятая, точка или нуль-терминатор
			{
				if (min == 0) 
					min = k;	// если min=0 это значит что мы нашли первое слово и минимальным значением по умолчанию будет длина первого слова
				if (k < min)
					min = k;	// если длина слова меньше min то присваиваем новое значение для min
				k = 0;	// обнуляем длину слова
			}
		}
		cout << "Длина самого короткого слова в символах равна " << min;
	}
	return 0;
}