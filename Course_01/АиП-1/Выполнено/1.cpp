#include <iostream>

using namespace std;

int main()
{
	setlocale(LC_ALL, "rus");
	double sum=0, n, v=2;	// объявление переменных
	cout << "Введите положительное n для подсчета суммы ряда 1/2^n: ";
	cin >> n;
	if (n == 0) cout << "Сумма ряда: " << 1 << endl;	// любое число в степени 0 = 1, соответственно сумма ряда будет равна 1
	else {
		for (int i = 1; i <= n; i++, v *= 2)	// цикл прибавляющий к сумме дробь с знаменателем, домножаемым на 2 каждую итерацию цикла
		{
			sum += (1 / v);
		}
		cout << "Сумма ряда: " << sum;
	}
}