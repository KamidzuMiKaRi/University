#include <iostream>

using namespace std;

bool Bool7(int K)	// булева функция, определяющая, является ли число К степенью числа 7
{	
	int i = 1;
	while (i < K) {
		i *= 7;
	}
	return i == K;
}

int main()
{
	setlocale(LC_ALL, "rus");
	int i=0, K, answer=0;
	cout << "Введите положительное число больше нуля.\n";
	do {
		cin >> K;
		if (K < 1)
		{
			cout << "Попытайтесь снова\n";
			continue;	// если переменная не удовлетворяет, то новая итерация
		}
		else {	// если соответствует, то действуем
			if (Bool7(K) == 1)	// вызов функции, если ответ 1 то
			{
				cout << "Число " << K << " является степенью числа 7.\n"; // выводим сообщение о удовлетворении
				i++;	// увеличиваем счетчик цикла на 1
				answer++;	// увеличиваем счетчик чисел на 1
			}
			else cout << "Число " << K << " не является степенью числа 7\n"; // иначе сообщение об отрицательном результате
		}
	} while (i < 5);	// цикл нацелен на ввод 5 положительных переменных
	cout << "Итого в наборе из 5 положительных чисел " << answer << " являются степенью числа 7";	// вывод результата
	return 0;
}