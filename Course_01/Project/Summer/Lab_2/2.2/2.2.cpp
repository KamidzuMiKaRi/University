#include <iostream>
#include <cstdlib>

using namespace std;

int main() 
{
    setlocale(LC_ALL, "Russian");
    int K, N;
    cout << "Введите число столбиков: ";
    cin >> N;
    cout << "Укажите максимальную длину прыжка: ";
    cin >> K;
    int* arr = new int[N];    // основной массив. тут будет указана стоимость прыжка, отнимут или прибавят деньги (монеты)
    cout << "Заполняем стоимость столбцов случайными числами:" << endl;
    for (int i = 0; i < N; i++)
    {
        arr[i] = rand() % (10 - -10 + 1) - 10;; // генерируем случайное число от 1 до 9;
    }
    for (int i = 0; i < N; i++)
    {
        cout << arr[i] << " ";
    }
    cout << endl;
    int* MAX = new int[N]; // массив с наилучшим исходом для столбца
    int* previous = new int[N]; // массив для хранения предыдущего столбца
    MAX[0] = arr[0]; // первый стобец тоже имеет цену, поэтому присваиваем его стоимость к максимальной сумме
    previous[0] = -1; // отрицательное значение первого столбика не даст вернуться не туда
    for (int i = 1; i < N; i++) // считаем максимальное число денег для каждого стобика
    {
        MAX[i] = arr[i];
        previous[i] = i - 1;
        for (int j = i - 1; j >= max(0, i - K); j--)    // проверка предыдущих стобцов в зоне прыжка (функция макс для предела счёта)
        {
            if (MAX[j] + arr[i] > MAX[i])   // если от числа на стобике сумма станет больше, то действуем
            {
                MAX[i] = MAX[j] + arr[i];
                previous[i] = j;
            }
        }
    }
    int here = N - 1;    // текущий столбик
    int jump = 0;
    int* itwas = new int[N]; // массив посещенных (было - it was) столбиков
    while (here != -1)   // показываем наилучший путь кузнечика, пока не дойдем до первого столбика
    {
        itwas[jump] = here + 1; // Записываем текущий столбик в массив посещенных
        here = previous[here]; // Переходим к предыдущему столбику
        jump++; // следующий прыжок
    }
    cout << "Количество собранных монет: " << MAX[N - 1] << endl;
    cout << "Количество прыжков: " << jump - 1 << endl;
    cout << "Посещенные столбики: ";       // список посещенных столбиков в перевернутом порядке
    for (int i = jump - 1; i >= 0; i--) 
    {
        cout << itwas[i] << " ";
    }
    cout << endl;
    delete[] arr;
    delete[] MAX;
    delete[] previous;
    delete[] itwas;
    return 0;
}
